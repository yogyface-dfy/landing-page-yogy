/** Drapeau emoji depuis le code ISO (FR → 🇫🇷). */
export function flagEmoji(iso) {
  return String(iso || '')
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)))
}

